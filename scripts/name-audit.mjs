// Reports accessible names that cannot tell controls apart, read from the accessibility tree
// (Playwright ariaSnapshot). Report-only: findings do not fail the run unless --strict.
// Requires a docs server (pnpm dev, or a built preview) at DOCS_URL.
//
//   DOCS_URL=http://localhost:5193 node scripts/name-audit.mjs [slug-or-route…] \
//     [--site] [--only light-desktop] [--report file.json] [--strict] [--list]
//   --list prints the page ids that would run (site: routes, matched exactly) and exits.
//
// Status words follow the repository convention:
//   FAIL     at least one R2/R3 finding on the page (exit 0 unless --strict)
//   NOT_RUN  the page failed to load or threw (exit 1)
//   PASS     no finding
//   UNVERIFIED (scope note) popups, menus and dialogs that are not open at rest are not in the tree.
//
// Default: every [data-playground] [data-demo] is a root of its own (the same name in two demos is
// fine). --site scans the site's pages with <main> (else <body>) as the root, default language only.
// Names do not change with the theme and the library has no mobile scope, so one variant runs by default.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { closeWithTimeout, selectVariants, withBrowser } from "./browser-runtime.mjs";
import { findNameIssues, parseAriaSnapshot } from "./lib/name-check.mjs";

const args = process.argv.slice(2);
const valueFlags = new Set(["--only", "--report"]);
const boolFlags = new Set(["--site", "--strict", "--list"]);
for (let i = 0; i < args.length; i++) {
  if (!args[i].startsWith("--")) continue;
  if (boolFlags.has(args[i])) continue;
  if (!valueFlags.has(args[i])) throw new Error(`unknown flag: ${args[i]}`);
  if (!args[i + 1] || args[i + 1].startsWith("--")) throw new Error(`missing value for ${args[i]}`);
  i++;
}
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const reportPath = flag("--report");
const site = args.includes("--site");
const strict = args.includes("--strict");
const requested = args.filter((a, i) => !a.startsWith("--") && !valueFlags.has(args[i - 1]));
const variants = selectVariants(flag("--only") ?? "light-desktop");
const base = process.env.DOCS_URL ?? "http://localhost:5180";
const docs = (path) => fileURLToPath(new URL(`../apps/docs/${path}`, import.meta.url));

function playgroundPages() {
  const slugs = requested.length
    ? requested
    : readdirSync(docs("src/content"), { withFileTypes: true })
      .filter((d) => d.isDirectory() && !d.name.startsWith(".")).map((d) => d.name).sort();
  return slugs.map((slug) => ({ id: slug, path: `/playground/${slug}` }));
}

/** Site routes: the sitemap (generated by the docs build from nav + registry) plus /components and the examples. */
function siteRoutes() {
  let sitemap;
  try { sitemap = readFileSync(docs("public/sitemap.xml"), "utf8"); }
  catch { throw new Error("apps/docs/public/sitemap.xml is missing; run `pnpm --filter docs build` first"); }
  const routes = new Set(["/"]);
  for (const [, loc] of sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)) {
    const path = new URL(loc).pathname.replace(/\/$/, "") || "/";
    if (path !== "/en" && !path.startsWith("/en/")) routes.add(path);
  }
  routes.add("/components");
  // Examples: ids from the gallery list, nested workspace routes from its route table's data.
  const list = readFileSync(docs("src/examples/list.ts"), "utf8");
  const examples = [...list.matchAll(/^\s*id: "(\w+)",$/gm)].map((m) => m[1]);
  routes.add("/examples");
  for (const id of examples) routes.add(`/examples/${id}`);
  if (examples.includes("workspace")) {
    const shell = readFileSync(docs("src/examples/workspace/shell.tsx"), "utf8");
    const settings = (/export const SETTINGS = \[(.*?)\] as const/s.exec(shell)?.[1] ?? "").matchAll(/id: "(\w+)"/g);
    const data = readFileSync(docs("src/examples/workspace/data.ts"), "utf8");
    const block = /export const COLLECTIONS[^=]*=\s*\[(.*?)\n\];/s.exec(data)?.[1] ?? "";
    for (const sub of ["collections", "help"]) routes.add(`/examples/workspace/${sub}`);
    for (const [, id] of settings) routes.add(`/examples/workspace/settings/${id}`);
    for (const [, id] of block.matchAll(/^\s*\{ id: "(\w+)", name:/gm)) routes.add(`/examples/workspace/collections/${id}`);
  }
  return [...routes].map((path) => ({ id: path, path }));
}

const pages = site ? siteRoutes() : playgroundPages();
const selected = requested.length && site ? pages.filter((p) => requested.includes(p.path)) : pages;

if (args.includes("--list")) {
  console.log(selected.map((p) => p.id).join("\n"));
  process.exit(0);
}

const findings = []; // { page, variant, unit, rule, role, name, scope, count }
const results = []; // { page, variant, status, units, findings }
const problems = [];
let interrupted = false;
const onInterrupt = () => { interrupted = true; };
process.on("SIGINT", onInterrupt);
process.on("SIGTERM", onInterrupt);

try {
  await withBrowser(async (browser) => {
    for (const v of variants) {
      if (interrupted) throw new Error("name audit interrupted");
      const context = await browser.newContext({
        viewport: { width: v.width, height: v.height },
        colorScheme: v.theme, reducedMotion: "reduce",
      });
      try {
        const page = await context.newPage();
        let pageError;
        page.on("pageerror", (error) => { pageError ??= error.message; });
        for (const target of selected) {
          if (interrupted) throw new Error("name audit interrupted");
          pageError = undefined;
          try {
            await page.goto(`${base}${target.path}${site ? "" : `?theme=${v.theme}`}`, { waitUntil: "networkidle", timeout: 30000 });
            const snapshots = [];
            if (site) {
              const main = page.locator("main").first();
              await main.waitFor({ timeout: 8000 }).catch(() => {});
              const root = (await page.locator("main").count()) ? main : page.locator("body");
              await page.waitForTimeout(250);
              snapshots.push({ unit: "main", text: await root.ariaSnapshot() });
            } else {
              await page.waitForFunction(() =>
                document.querySelector("[data-playground] [data-demo]") ||
                document.querySelector('[data-slot="empty"][data-state="empty"]'),
              undefined, { timeout: 15000 });
              await page.waitForTimeout(250);
              const demos = page.locator("[data-playground] [data-demo]");
              const count = await demos.count();
              for (let i = 0; i < count; i++) snapshots.push({ unit: `demo ${i + 1}`, text: await demos.nth(i).ariaSnapshot() });
            }
            if (pageError) throw new Error(`page error: ${pageError}`);
            const own = [];
            for (const s of snapshots) {
              for (const issue of findNameIssues(parseAriaSnapshot(s.text))) own.push({ page: target.id, variant: v.name, unit: s.unit, ...issue });
            }
            findings.push(...own);
            const status = own.length ? "FAIL" : "PASS";
            results.push({ page: target.id, variant: v.name, status, units: snapshots.length, findings: own.length });
            console.log(`names ${target.id} [${v.name}] ${status} units ${snapshots.length} R2 ${own.filter((f) => f.rule === "R2").length} R3 ${own.filter((f) => f.rule === "R3").length}`);
          } catch (error) {
            results.push({ page: target.id, variant: v.name, status: "NOT_RUN", units: 0, findings: 0 });
            problems.push(`NOT_RUN ${target.id} [${v.name}] ${error.message.split("\n")[0].slice(0, 160)}`);
          }
        }
      } finally {
        try { await closeWithTimeout(context, "context"); }
        catch (error) { problems.push(`${v.name} context cleanup ${error.message}`); }
      }
    }
  });
} catch (error) {
  problems.push(`harness ${error.message}`);
}
process.off("SIGINT", onInterrupt);
process.off("SIGTERM", onInterrupt);

/** (rule, role, name) -> { count, pages } */
const aggregate = new Map();
for (const f of findings) {
  const key = `${f.rule}\0${f.role}\0${f.name}`;
  const entry = aggregate.get(key) ?? { rule: f.rule, role: f.role, name: f.name, occurrences: 0, pages: new Set() };
  entry.occurrences++;
  entry.pages.add(f.page);
  aggregate.set(key, entry);
}
const ranked = [...aggregate.values()].sort((a, b) => b.pages.size - a.pages.size || b.occurrences - a.occurrences);
const count = (status) => results.filter((r) => r.status === status).length;
const counts = { PASS: count("PASS"), FAIL: count("FAIL"), NOT_RUN: count("NOT_RUN") };
const byRule = { R2: findings.filter((f) => f.rule === "R2").length, R3: findings.filter((f) => f.rule === "R3").length };
const status = problems.length ? "NOT_RUN" : findings.length ? "FAIL" : "PASS";
const exitCode = problems.length || (strict && findings.length) ? 1 : 0;
const report = {
  base, mode: site ? "site" : "playground", strict, variants: variants.map((v) => v.name),
  scopeNote: "UNVERIFIED: popups, menus and dialogs that are not open at rest are not in the tree.",
  pages: results.length, counts, findingsByRule: byRule, status, exitCode,
  aggregate: ranked.map((e) => ({ rule: e.rule, role: e.role, name: e.name, occurrences: e.occurrences, pages: [...e.pages] })),
  findings, results, problems,
};
if (reportPath) writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);
console.log(`\n${report.mode}: ${results.length} page run(s): PASS ${counts.PASS} FAIL ${counts.FAIL} NOT_RUN ${counts.NOT_RUN}; findings R2 ${byRule.R2} R3 ${byRule.R3}`);
for (const e of ranked.slice(0, 20)) {
  const where = [...e.pages];
  console.log(`  ${e.rule} ${e.role} "${e.name}" ×${e.occurrences} on ${where.length} page(s): ${where.slice(0, 4).join(", ")}${where.length > 4 ? ", …" : ""}`);
}
if (ranked.length > 20) console.log(`  … ${ranked.length - 20} more (see --report)`);
console.log("UNVERIFIED  popups, menus and dialogs that are not open at rest are not in the tree.");
if (problems.length) console.log(`\n${problems.join("\n")}`);
console.log(`\n${status}${strict ? " (strict)" : " (report only)"}`);
process.exitCode = exitCode;
