// Reports accessible names that cannot tell controls apart, read from the accessibility tree
// (Playwright ariaSnapshot). Report-only: findings do not fail the run unless --strict.
// Requires a docs server (pnpm dev, or a built preview) at DOCS_URL.
//
//   DOCS_URL=http://localhost:5193 node scripts/name-audit.mjs [slug-or-route…] \
//     [--site] [--lang en] [--popups] [--only light-desktop] [--report file.json] [--strict] [--list]
//   --list prints the page ids that would run (site: routes, matched exactly) and exits.
//   --lang en scans the English pages (/en/playground/<slug>, or the site's /en routes) instead of the default language.
//   --popups also opens every [aria-haspopup] trigger in each unit, one at a time, and checks the opened popup
//            (dialog, alertdialog, menu, listbox) as a unit of its own, then closes it with Escape.
//
// Status words follow the repository convention:
//   FAIL     at least one R2/R3 finding on the page (exit 0 unless --strict); specimens count too
//   SPECIMEN (column, not a status) an R2 whose every match sits inside a [data-specimen] region the demo
//            or page declared (one control laid out in several looks). Reported in its own list; the page
//            stays FAIL and --strict still fails on it. The script holds no list of pages or names.
//   NOT_RUN  the page failed to load or threw (exit 1)
//   PASS     no finding
//   UNVERIFIED (scope note) without --popups, popups, menus and dialogs that are not open at rest are not in the tree;
//            with it, popups opened from inside a popup, by hover or by keyboard only, and triggers without
//            aria-haspopup are still not visited; each page also lists the triggers it could not check:
//            popupUnopened (clicked, nothing new opened), popupHidden (not visible at rest), popupCapped (past 24).
//
// Default: every [data-playground] [data-demo] is a root of its own (the same name in two demos is
// fine). --site scans the site's pages with <main> (else <body>) as the root, default language unless --lang en.
// Names do not change with the theme and the library has no mobile scope, so one variant runs by default.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { closeWithTimeout, selectVariants, withBrowser } from "./browser-runtime.mjs";
import { findNameIssues, parseAriaSnapshot, splitSpecimens } from "./lib/name-check.mjs";

const args = process.argv.slice(2);
const valueFlags = new Set(["--only", "--report", "--lang"]);
const boolFlags = new Set(["--site", "--strict", "--list", "--popups"]);
for (let i = 0; i < args.length; i++) {
  if (!args[i].startsWith("--")) continue;
  if (boolFlags.has(args[i])) continue;
  if (!valueFlags.has(args[i])) throw new Error(`unknown flag: ${args[i]}`);
  if (!args[i + 1] || args[i + 1].startsWith("--")) throw new Error(`missing value for ${args[i]}`);
  i++;
}
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const reportPath = flag("--report");
const site = args.includes("--site");
const strict = args.includes("--strict");
const popups = args.includes("--popups");
const lang = flag("--lang") ?? "zh";
if (lang !== "zh" && lang !== "en") throw new Error(`--lang must be zh or en, got ${lang}`);
const english = lang === "en";
const requested = args.filter((a, i) => !a.startsWith("--") && !valueFlags.has(args[i - 1]));
const variants = selectVariants(flag("--only") ?? "light-desktop");
const base = process.env.DOCS_URL ?? "http://localhost:5180";
const docs = (path) => fileURLToPath(new URL(`../apps/docs/${path}`, import.meta.url));

function playgroundPages() {
  const slugs = requested.length
    ? requested
    : readdirSync(docs("src/content"), { withFileTypes: true })
      .filter((d) => d.isDirectory() && !d.name.startsWith(".")).map((d) => d.name).sort();
  return slugs.map((slug) => ({ id: slug, path: `${english ? "/en" : ""}/playground/${slug}` }));
}

/** Site routes: the sitemap (generated by the docs build from nav + registry) plus /components and the examples. */
function siteRoutes() {
  let sitemap;
  try { sitemap = readFileSync(docs("public/sitemap.xml"), "utf8"); }
  catch { throw new Error("apps/docs/public/sitemap.xml is missing; run `pnpm --filter docs build` first"); }
  const routes = new Set([english ? "/en" : "/"]);
  for (const [, loc] of sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)) {
    const path = new URL(loc).pathname.replace(/\/$/, "") || "/";
    if ((path === "/en" || path.startsWith("/en/")) === english) routes.add(path);
  }
  const prefix = english ? "/en" : "";
  const add = (path) => routes.add(`${prefix}${path}`);
  add("/components");
  // Examples: ids from the gallery list, nested workspace routes from its route table's data.
  const list = readFileSync(docs("src/examples/list.ts"), "utf8");
  const examples = [...list.matchAll(/^\s*id: "(\w+)",$/gm)].map((m) => m[1]);
  add("/examples");
  for (const id of examples) add(`/examples/${id}`);
  if (examples.includes("workspace")) {
    const shell = readFileSync(docs("src/examples/workspace/shell.tsx"), "utf8");
    const settings = (/export const SETTINGS = \[(.*?)\] as const/s.exec(shell)?.[1] ?? "").matchAll(/id: "(\w+)"/g);
    const data = readFileSync(docs("src/examples/workspace/data.ts"), "utf8");
    const block = /export const COLLECTIONS[^=]*=\s*\[(.*?)\n\];/s.exec(data)?.[1] ?? "";
    for (const sub of ["collections", "help"]) add(`/examples/workspace/${sub}`);
    for (const [, id] of settings) add(`/examples/workspace/settings/${id}`);
    for (const [, id] of block.matchAll(/^\s*\{ id: "(\w+)", name:/gm)) add(`/examples/workspace/collections/${id}`);
  }
  return [...routes].map((path) => ({ id: path, path }));
}

/** The finding's scope (`region "a" > group "b"`, every segment named) as a locator under the unit root. */
function scopeOf(root, path) {
  if (path === "(root)") return root;
  let scope = root;
  for (const segment of path.split(" > ")) {
    const m = /^(\w+) "(.*)"$/.exec(segment);
    if (!m) return root;
    scope = scope.getByRole(m[1], { name: m[2], exact: true });
  }
  return scope;
}

const POPUP = '[role="dialog"], [role="alertdialog"], [role="menu"], [role="listbox"]';
const TRIGGER = '[aria-haspopup]:not([aria-haspopup="false"]):not([disabled]):not([aria-disabled="true"])';

/**
 * Opens each popup trigger in a unit, one at a time, and checks the opened popup as a unit of its own;
 * returns what was tried so nothing passes silently: popups checked, triggers past the cap, triggers not
 * visible at rest, and the labels of visible triggers whose click opened nothing new (those stay UNVERIFIED).
 * The popup is the newest visible dialog/menu/listbox that was not visible before the click. The page is reloaded when Escape does
 * not close the popup or the click navigated, so the next trigger starts from rest.
 */
const MAX_TRIGGERS = 24;
async function openPopups(page, unit, check) {
  const tally = { opened: 0, hidden: 0, capped: 0, unopened: [] };
  const triggers = unit.root.locator(TRIGGER);
  const all = await triggers.count();
  const total = Math.min(all, MAX_TRIGGERS);
  tally.capped = all - total;
  const url = page.url();
  const visible = () => page.locator(POPUP).filter({ visible: true });
  for (let i = 0; i < total; i++) {
    const trigger = triggers.nth(i);
    if (!(await trigger.isVisible().catch(() => false))) { tally.hidden++; continue; }
    const label = ((await trigger.getAttribute("aria-label")) ?? (await trigger.textContent()) ?? "").replace(/\s+/g, " ").trim().slice(0, 40);
    const before = await visible().count();
    await trigger.click({ timeout: 2000 }).catch(() => {});
    await page.waitForTimeout(300);
    const after = visible();
    if (await after.count() > before) {
      const popup = after.last();
      await check({ unit: `${unit.unit} > popup "${label}"`, root: popup, text: await popup.ariaSnapshot() });
      tally.opened++;
    } else tally.unopened.push(`${unit.unit} > "${label}"`);
    await page.keyboard.press("Escape");
    await page.waitForTimeout(150);
    if (page.url() !== url || await visible().count() > before) {
      await page.goto(url, { waitUntil: "networkidle", timeout: 30000 });
      await page.waitForTimeout(250);
    }
  }
  return tally;
}

const pages = site ? siteRoutes() : playgroundPages();
const selected = requested.length && site ? pages.filter((p) => requested.includes(p.path)) : pages;

if (args.includes("--list")) {
  console.log(selected.map((p) => p.id).join("\n"));
  process.exit(0);
}

const findings = []; // { page, variant, unit, rule, role, name, scope, count }
const specimens = []; // same shape; R2 inside a declared [data-specimen] region
const results = []; // { page, variant, status, units, findings }
const problems = [];
let interrupted = false;
const onInterrupt = () => { interrupted = true; };
process.on("SIGINT", onInterrupt);
process.on("SIGTERM", onInterrupt);

try {
  await withBrowser(async (browser) => {
    for (const v of variants) {
      if (interrupted) throw new Error("name audit interrupted");
      const context = await browser.newContext({
        viewport: { width: v.width, height: v.height },
        colorScheme: v.theme, reducedMotion: "reduce",
      });
      try {
        const page = await context.newPage();
        let pageError;
        page.on("pageerror", (error) => { pageError ??= error.message; });
        for (const target of selected) {
          if (interrupted) throw new Error("name audit interrupted");
          pageError = undefined;
          try {
            await page.goto(`${base}${target.path}${site ? "" : `?theme=${v.theme}`}`, { waitUntil: "networkidle", timeout: 30000 });
            const snapshots = [];
            if (site) {
              const main = page.locator("main").first();
              await main.waitFor({ timeout: 8000 }).catch(() => {});
              const root = (await page.locator("main").count()) ? main : page.locator("body");
              await page.waitForTimeout(250);
              snapshots.push({ unit: "main", root, text: await root.ariaSnapshot() });
            } else {
              await page.waitForFunction(() =>
                document.querySelector("[data-playground] [data-demo]") ||
                document.querySelector('[data-slot="empty"][data-state="empty"]'),
              undefined, { timeout: 15000 });
              await page.waitForTimeout(250);
              const demos = page.locator("[data-playground] [data-demo]");
              const count = await demos.count();
              for (let i = 0; i < count; i++) snapshots.push({ unit: `demo ${i + 1}`, root: demos.nth(i), text: await demos.nth(i).ariaSnapshot() });
            }
            const own = [];
            const ownSpecimens = [];
            // Checked while the unit is on screen: a popup unit is only resolvable while it is open.
            const check = async (s) => {
              const issues = findNameIssues(parseAriaSnapshot(s.text));
              // Is each control with this role and name inside a region the demo/page marked as a specimen?
              const flags = await Promise.all(issues.map((issue) => issue.rule !== "R2" ? [] :
                scopeOf(s.root, issue.scope).getByRole(issue.role, { name: issue.name, exact: true })
                  .evaluateAll((els) => els.map((el) => el.closest("[data-specimen]") !== null))));
              const split = splitSpecimens(issues, flags);
              for (const issue of split.issues) own.push({ page: target.id, variant: v.name, unit: s.unit, ...issue });
              for (const issue of split.specimens) ownSpecimens.push({ page: target.id, variant: v.name, unit: s.unit, ...issue });
            };
            for (const s of snapshots) await check(s);
            const popup = { popupUnits: 0, popupHidden: 0, popupCapped: 0, popupUnopened: [] };
            if (popups) for (const s of snapshots) {
              const t = await openPopups(page, s, check);
              popup.popupUnits += t.opened; popup.popupHidden += t.hidden; popup.popupCapped += t.capped; popup.popupUnopened.push(...t.unopened);
            }
            if (pageError) throw new Error(`page error: ${pageError}`);
            findings.push(...own);
            specimens.push(...ownSpecimens);
            const status = own.length || ownSpecimens.length ? "FAIL" : "PASS";
            results.push({ page: target.id, variant: v.name, status, units: snapshots.length, ...(popups ? popup : {}), findings: own.length, specimens: ownSpecimens.length });
            console.log(`names ${target.id} [${v.name}] ${status} units ${snapshots.length}+${popup.popupUnits}${popups ? ` (unopened ${popup.popupUnopened.length}, hidden ${popup.popupHidden}, capped ${popup.popupCapped})` : ""} R2 ${own.filter((f) => f.rule === "R2").length} R3 ${own.filter((f) => f.rule === "R3").length} specimen ${ownSpecimens.length}`);
          } catch (error) {
            results.push({ page: target.id, variant: v.name, status: "NOT_RUN", units: 0, findings: 0, specimens: 0 });
            problems.push(`NOT_RUN ${target.id} [${v.name}] ${error.message.split("\n")[0].slice(0, 160)}`);
          }
        }
      } finally {
        try { await closeWithTimeout(context, "context"); }
        catch (error) { problems.push(`${v.name} context cleanup ${error.message}`); }
      }
    }
  });
} catch (error) {
  problems.push(`harness ${error.message}`);
}
process.off("SIGINT", onInterrupt);
process.off("SIGTERM", onInterrupt);

/** (rule, role, name) -> { count, pages }, most widespread first */
function rank(list) {
  const aggregate = new Map();
  for (const f of list) {
    const key = `${f.rule}\0${f.role}\0${f.name}`;
    const entry = aggregate.get(key) ?? { rule: f.rule, role: f.role, name: f.name, occurrences: 0, pages: new Set() };
    entry.occurrences++;
    entry.pages.add(f.page);
    aggregate.set(key, entry);
  }
  return [...aggregate.values()].sort((a, b) => b.pages.size - a.pages.size || b.occurrences - a.occurrences);
}
const ranked = rank(findings);
const rankedSpecimens = rank(specimens);
const listed = (e) => ({ rule: e.rule, role: e.role, name: e.name, occurrences: e.occurrences, pages: [...e.pages] });
const count = (status) => results.filter((r) => r.status === status).length;
const counts = { PASS: count("PASS"), FAIL: count("FAIL"), NOT_RUN: count("NOT_RUN") };
const byRule = { R2: findings.filter((f) => f.rule === "R2").length, R3: findings.filter((f) => f.rule === "R3").length };
const status = problems.length ? "NOT_RUN" : findings.length || specimens.length ? "FAIL" : "PASS";
const exitCode = problems.length || (strict && (findings.length || specimens.length)) ? 1 : 0;
const report = {
  base, mode: site ? "site" : "playground", lang, popups, strict, variants: variants.map((v) => v.name),
  scopeNote: popups
    ? "UNVERIFIED: popups opened from inside a popup, by hover or keyboard only, or by triggers without aria-haspopup; per page, triggers whose click opened nothing (popupUnopened), triggers hidden at rest (popupHidden) and triggers past the per-unit cap (popupCapped)."
    : "UNVERIFIED: popups, menus and dialogs that are not open at rest are not in the tree.",
  pages: results.length, counts, findingsByRule: byRule, specimenCount: specimens.length, status, exitCode,
  aggregate: ranked.map(listed), specimenAggregate: rankedSpecimens.map(listed),
  findings, specimens, results, problems,
};
if (reportPath) writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);
console.log(`\n${report.mode}: ${results.length} page run(s): PASS ${counts.PASS} FAIL ${counts.FAIL} NOT_RUN ${counts.NOT_RUN}; findings R2 ${byRule.R2} R3 ${byRule.R3}; specimen ${specimens.length}`);
for (const e of ranked.slice(0, 20)) {
  const where = [...e.pages];
  console.log(`  ${e.rule} ${e.role} "${e.name}" ×${e.occurrences} on ${where.length} page(s): ${where.slice(0, 4).join(", ")}${where.length > 4 ? ", …" : ""}`);
}
if (ranked.length > 20) console.log(`  … ${ranked.length - 20} more (see --report)`);
if (rankedSpecimens.length) console.log("SPECIMEN  declared side-by-side looks of one control (data-specimen); still counted:");
for (const e of rankedSpecimens) console.log(`  ${e.rule} ${e.role} "${e.name}" ×${e.occurrences} on ${e.pages.size} page(s): ${[...e.pages].slice(0, 4).join(", ")}${e.pages.size > 4 ? ", …" : ""}`);
console.log(`UNVERIFIED  ${report.scopeNote.replace(/^UNVERIFIED: /, "")}`);
if (problems.length) console.log(`\n${problems.join("\n")}`);
console.log(`\n${status}${strict ? " (strict)" : " (report only)"}`);
process.exitCode = exitCode;
